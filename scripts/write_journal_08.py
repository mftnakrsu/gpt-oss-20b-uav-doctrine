"""Compose docs/journal/08-phase-a-ablation-sweep.md from v1/v2/v3/v4 artifacts.

Inputs (per variant in {v1,v2,v3,v4}):
  outputs/<v>_run_summary.json
  outputs/<v>_metrics.jsonl
  outputs/<v>_eval_summary.json
  outputs/<v>_samples.jsonl
  outputs/<v>_test_results.jsonl
  outputs/<v>_held_out_source_results.jsonl

Output:
  docs/journal/08-phase-a-ablation-sweep.md
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"
VARIANTS = ("v1", "v2", "v3", "v4")
VARIANT_DESCRIPTIONS = {
    "v1": "baseline (rank 16, no_sysprompt, 2 epochs, lr 1e-4)",
    "v2": "rank 16 → **32** (+capacity)",
    "v3": "2 → **3 epochs** (+training)",
    "v4": "lr 1e-4 → **2e-4** (+step size)",
}


def read_json(path: Path) -> dict:
    return json.loads(path.read_text()) if path.exists() else {}


def read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def fmt_secs(s: float) -> str:
    s = int(s)
    h, s = divmod(s, 3600)
    m, s = divmod(s, 60)
    return f"{h}h{m:02d}m" if h else f"{m}m{s:02d}s"


def load_variant(v: str) -> dict[str, Any]:
    return {
        "summary": read_json(OUT / f"{v}_run_summary.json"),
        "eval": read_json(OUT / f"{v}_eval_summary.json"),
        "samples": read_jsonl(OUT / f"{v}_samples.jsonl"),
        "test_results": read_jsonl(OUT / f"{v}_test_results.jsonl"),
        "held_results": read_jsonl(OUT / f"{v}_held_out_source_results.jsonl"),
        "metrics": read_jsonl(OUT / f"{v}_metrics.jsonl"),
    }


def fmt_table_row(*cells: Any) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        default=str(ROOT / "docs" / "journal" / "08-phase-a-ablation-sweep.md"),
        type=Path,
    )
    parser.add_argument(
        "--shared-samples", type=int, default=5,
        help="Number of test prompts to show across all variants (apples-to-apples comparison)",
    )
    args = parser.parse_args()

    variants: dict[str, dict[str, Any]] = {v: load_variant(v) for v in VARIANTS}

    lines: list[str] = []
    lines.append("# Phase A ablation sweep — gpt-oss-20b SFT (v1/v2/v3/v4)")
    lines.append("")
    lines.append(
        "_Generated by `scripts/write_journal_08.py` from the per-variant "
        "run + eval summary artifacts. Re-running overwrites this file._"
    )
    lines.append("")

    # =====================
    # Ablation design
    # =====================
    lines.append("## Ablation design")
    lines.append("")
    lines.append(
        "Single-axis variants vs the v1 baseline so each delta is attributable. "
        "Per the 2026 Unsloth GPT-OSS guidance, the reasoning-renderer variant "
        "was deliberately omitted — switching to `gpt_oss_medium_reasoning` on "
        "Q&A pairs **without** CoT traces in the assistant turn doesn't add "
        "reasoning capability and can suppress it. A reasoning-render experiment "
        "requires regenerating training data with CoT first (Phase A.5)."
    )
    lines.append("")
    lines.append("| variant | description |")
    lines.append("|---|---|")
    for v in VARIANTS:
        lines.append(f"| `{v}` | {VARIANT_DESCRIPTIONS[v]} |")
    lines.append("")

    # =====================
    # Training summary
    # =====================
    lines.append("## Training summary")
    lines.append("")
    lines.append(
        "| variant | steps | min_smooth_train_nll | final_val_nll | wall | tokens | est. cost |"
    )
    lines.append("|---|---:|---:|---:|---:|---:|---:|")
    for v in VARIANTS:
        s = variants[v]["summary"]
        if not s:
            lines.append(fmt_table_row(v, "—", "—", "—", "—", "—", "—"))
            continue
        lines.append(
            fmt_table_row(
                v,
                s.get("step", 0),
                f"{s.get('min_smoothed_train_nll', 0):.4f}",
                f"{s.get('final_val_nll', 0) or 0:.4f}",
                fmt_secs(s.get("wall_seconds", 0)),
                f"{s.get('tokens_processed', 0):,}",
                f"${s.get('estimated_cost_usd', 0):.2f}",
            )
        )
    lines.append("")

    # =====================
    # Eval — test set
    # =====================
    lines.append("## Test set evaluation")
    lines.append("")
    lines.append("Mean NLL on `test.jsonl` (1,875 examples, ChatML, computed via teacher-forced compute_logprobs).")
    lines.append("")
    lines.append("| variant | n | mean_nll | Δ vs v1 |")
    lines.append("|---|---:|---:|---:|")
    base_test = (variants["v1"]["eval"].get("test") or {}).get("mean_nll")
    for v in VARIANTS:
        agg = (variants[v]["eval"].get("test") or {})
        n = agg.get("n", 0)
        nll = agg.get("mean_nll")
        delta = (nll - base_test) if (nll is not None and base_test is not None) else None
        lines.append(
            fmt_table_row(
                v, n,
                f"{nll:.4f}" if nll is not None else "—",
                f"{delta:+.4f}" if delta is not None else "—",
            )
        )
    lines.append("")

    # Per question type
    lines.append("### By question type (mean_nll)")
    lines.append("")
    qtypes = sorted({
        qt
        for v in VARIANTS
        for qt in (variants[v]["eval"].get("test", {}).get("by_question_type") or {})
    })
    if qtypes:
        header = "| variant | " + " | ".join(qtypes) + " |"
        sep = "|---|" + "|".join(["---:"] * len(qtypes)) + "|"
        lines.append(header)
        lines.append(sep)
        for v in VARIANTS:
            by_qt = variants[v]["eval"].get("test", {}).get("by_question_type") or {}
            row = [v]
            for qt in qtypes:
                stats = by_qt.get(qt) or {}
                if stats:
                    row.append(f"{stats['mean_nll']:.4f} (n={stats['n']})")
                else:
                    row.append("—")
            lines.append(fmt_table_row(*row))
        lines.append("")

    # =====================
    # Eval — held-out
    # =====================
    lines.append("## Held-out-source evaluation")
    lines.append("")
    lines.append("15 examples across 2 sources never seen during training (CRS C-UAS, FAA lost-link). Small sample — treat as qualitative.")
    lines.append("")
    lines.append("| variant | n | mean_nll | Δ vs v1 |")
    lines.append("|---|---:|---:|---:|")
    base_held = (variants["v1"]["eval"].get("held_out_source") or {}).get("mean_nll")
    for v in VARIANTS:
        agg = variants[v]["eval"].get("held_out_source") or {}
        n = agg.get("n", 0)
        nll = agg.get("mean_nll")
        delta = (nll - base_held) if (nll is not None and base_held is not None) else None
        lines.append(
            fmt_table_row(
                v, n,
                f"{nll:.4f}" if nll is not None else "—",
                f"{delta:+.4f}" if delta is not None else "—",
            )
        )
    lines.append("")

    # =====================
    # Side-by-side samples
    # =====================
    lines.append("## Qualitative — same prompts across all four variants")
    lines.append("")
    lines.append(
        f"Same {args.shared_samples} prompts (deterministic via `random.seed=42` "
        "on `test.jsonl`) answered by every variant. Compare the model rows "
        "directly — they all saw the same data, just different hyperparameters."
    )
    lines.append("")

    # The samples files use the same SAMPLE_SEED + same test pool → same pair_ids.
    # Build {pair_id: {variant: sample}} keyed by v1's pair_id ordering.
    samples_by_variant: dict[str, dict[str, dict]] = {
        v: {s["pair_id"]: s for s in variants[v]["samples"]}
        for v in VARIANTS
    }
    v1_samples = variants["v1"]["samples"][: args.shared_samples]
    if not v1_samples:
        lines.append("_(no samples — eval not complete)_")
        lines.append("")
    else:
        for i, s in enumerate(v1_samples, 1):
            pid = s["pair_id"]
            lines.append(
                f"### Prompt {i} — `{pid}` (`{s['question_type']}`) — "
                f"`{s['source_filename']}`"
            )
            lines.append("")
            lines.append("**Q:** " + s["user_question"])
            lines.append("")
            lines.append("**Reference:**")
            lines.append("")
            lines.append("> " + s["reference_answer"].replace("\n", "\n> "))
            lines.append("")
            for v in VARIANTS:
                gen = (samples_by_variant[v].get(pid) or {}).get(
                    "model_generation", "_(missing)_"
                )
                lines.append(f"**`{v}`:**")
                lines.append("")
                gen_text = (gen or "_(empty)_")
                lines.append("> " + gen_text.replace("\n", "\n> "))
                lines.append("")

    # =====================
    # Winner + recommendation
    # =====================
    lines.append("## Winner & recommendation")
    lines.append("")
    best_test = None
    best_held = None
    best_test_v = None
    best_held_v = None
    for v in VARIANTS:
        t = (variants[v]["eval"].get("test") or {}).get("mean_nll")
        h = (variants[v]["eval"].get("held_out_source") or {}).get("mean_nll")
        if t is not None and (best_test is None or t < best_test):
            best_test = t
            best_test_v = v
        if h is not None and (best_held is None or h < best_held):
            best_held = h
            best_held_v = v
    if best_test_v:
        lines.append(
            f"- **Lowest test NLL:** `{best_test_v}` ({best_test:.4f})"
        )
    if best_held_v:
        lines.append(
            f"- **Lowest held-out NLL:** `{best_held_v}` ({best_held:.4f})"
        )
    lines.append("")
    lines.append(
        "Compare test vs held-out to detect overfitting: if the test winner has "
        "*worse* held-out than v1, that variant memorized rather than generalized. "
        "Read 5+ qualitative samples before declaring a winner — NLL doesn't "
        "always track answer quality."
    )
    lines.append("")

    # =====================
    # Anything weird
    # =====================
    lines.append("## Anything weird")
    lines.append("")
    weird: list[str] = []
    for v in VARIANTS:
        s = variants[v]["summary"]
        if s.get("abort_reason"):
            weird.append(f"- `{v}` aborted: {s['abort_reason']}")
    if not weird:
        weird.append("- All four variants ran to completion with no guardrail trips.")
    # Validation token counts sanity check
    weird.append(
        "- Pricing per token is a placeholder (ADR 0001, $0.40/1M); reconcile "
        "against the real Tinker invoice before quoting absolute $."
    )
    for w in weird:
        lines.append(w)
    lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
