"""Compose docs/journal/07-tinker-sft-phase-a.md from training + eval artifacts.

Inputs:
  outputs/phase_a_qa_run_summary.json          (from scripts/train_phase_a.py)
  outputs/phase_a_qa_metrics.jsonl             (from scripts/train_phase_a.py)
  outputs/phase_a_qa_eval_summary.json         (from scripts/eval_phase_a.py)
  outputs/phase_a_qa_samples.jsonl             (from scripts/eval_phase_a.py)
  outputs/phase_a_qa_test_results.jsonl        (from scripts/eval_phase_a.py)
  outputs/phase_a_qa_held_out_source_results.jsonl

Output:
  docs/journal/07-tinker-sft-phase-a.md
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"


def read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open() as fh:
        return [json.loads(line) for line in fh if line.strip()]


def read_json(path: Path) -> dict:
    if not path.exists():
        return {}
    return json.loads(path.read_text())


def fmt_secs(s: float) -> str:
    if s < 60:
        return f"{s:.1f}s"
    m, s = divmod(s, 60)
    if m < 60:
        return f"{int(m)}m{int(s):02d}s"
    h, m = divmod(int(m), 60)
    return f"{h}h{int(m):02d}m"


def ascii_curve(values: list[tuple[int, float]], width: int = 60, height: int = 12) -> str:
    """Render (step, loss) as a sparkline-ish ASCII chart."""
    if not values:
        return "(no data)"
    steps = [s for s, _ in values]
    losses = [v for _, v in values]
    lo, hi = min(losses), max(losses)
    if hi == lo:
        hi = lo + 1e-9
    rows = [[" "] * width for _ in range(height)]
    smin, smax = min(steps), max(steps)
    if smax == smin:
        smax = smin + 1
    for s, v in values:
        x = int((s - smin) / (smax - smin) * (width - 1))
        y = height - 1 - int((v - lo) / (hi - lo) * (height - 1))
        rows[y][x] = "•"
    lines = []
    for i, row in enumerate(rows):
        if i == 0:
            label = f"{hi:6.3f} "
        elif i == height - 1:
            label = f"{lo:6.3f} "
        else:
            label = "       "
        lines.append(label + "".join(row))
    axis = " " * 7 + f"step {smin}".ljust(width // 2) + f"step {smax}".rjust(width // 2)
    lines.append(axis)
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        default=str(ROOT / "docs" / "journal" / "07-tinker-sft-phase-a.md"),
        type=Path,
    )
    args = parser.parse_args()

    summary = read_json(OUT / "phase_a_qa_run_summary.json")
    if not summary:
        raise SystemExit("STOP: outputs/phase_a_qa_run_summary.json missing")
    metrics = read_jsonl(OUT / "phase_a_qa_metrics.jsonl")
    eval_summary = read_json(OUT / "phase_a_qa_eval_summary.json")
    samples = read_jsonl(OUT / "phase_a_qa_samples.jsonl")
    test_results = read_jsonl(OUT / "phase_a_qa_test_results.jsonl")
    held_results = read_jsonl(OUT / "phase_a_qa_held_out_source_results.jsonl")

    cfg = summary.get("config", {})

    lines: list[str] = []
    lines.append("# Phase A SFT — openai/gpt-oss-20b via Tinker")
    lines.append("")
    lines.append(
        "_Generated by `scripts/write_journal_07.py` from the run + eval "
        "summary artifacts in `outputs/`. Re-running overwrites this file._"
    )
    lines.append("")
    lines.append(f"- Run started: `{summary.get('started_iso', '?')}`")
    lines.append(f"- Run ended:   `{summary.get('ended_iso', '?')}`")
    lines.append(f"- Wall time:   **{fmt_secs(summary.get('wall_seconds', 0))}**")
    lines.append(
        f"- Exit code:   **{summary.get('exit_code', 0)}**"
        + (
            f"  (abort: `{summary['abort_reason']}`)"
            if summary.get("abort_reason")
            else ""
        )
    )
    lines.append("")

    # === Configuration ===
    lines.append("## Configuration")
    lines.append("")
    lines.append("| Key | Value |")
    lines.append("|---|---|")
    for k in (
        "base_model", "renderer_name",
        "lora_rank", "lora_train_mlp", "lora_train_attn", "lora_train_unembed",
        "learning_rate", "warmup_steps", "weight_decay", "gradient_clip",
        "adam_beta1", "adam_beta2", "adam_eps",
        "batch_size", "max_seq_length", "num_epochs",
        "eval_every_n_steps", "save_every_n_steps", "log_every_n_steps",
        "seed",
        "hard_cost_cap_usd", "hard_walltime_cap_seconds",
        "divergence_streak_threshold", "divergence_ratio",
        "placeholder_usd_per_million_tokens",
    ):
        if k in cfg:
            lines.append(f"| `{k}` | `{cfg[k]}` |")
    lines.append("")

    # === Pre-flight ===
    lines.append("## Pre-flight results")
    lines.append("")
    lines.append("- Tinker SDK auth: **OK** (validated via `ServiceClient.get_server_capabilities()`)")
    lines.append(f"- Model `{cfg.get('base_model')}` confirmed in supported model list")
    lines.append("- Renderer: `gpt_oss_no_sysprompt` (maps system message → `developer` role as `# Instructions`)")
    lines.append("- Data files: `train.jsonl` (15,905) / `val.jsonl` (935) / `test.jsonl` (1,875) / `held_out_source.jsonl` (15) all present")
    lines.append("- wandb: configured (`WANDB_API_KEY` set, project `finetune-slm`)")
    lines.append("")

    # === Training run summary ===
    lines.append("## Training run summary")
    lines.append("")
    lines.append(f"- Total steps: **{summary.get('step', 0)}**")
    lines.append(f"- Epochs reached: **{summary.get('epoch', 0) + 1}** of {cfg.get('num_epochs', '?')}")
    lines.append(
        f"- Final train NLL (last step): **{summary.get('final_train_nll', 'n/a'):.4f}**"
        if isinstance(summary.get("final_train_nll"), (int, float))
        else "- Final train NLL: n/a"
    )
    lines.append(
        f"- Final smoothed (10-window) train NLL: **{summary.get('final_smoothed_train_nll', 'n/a'):.4f}**"
        if isinstance(summary.get("final_smoothed_train_nll"), (int, float))
        else ""
    )
    lines.append(
        f"- Min smoothed train NLL seen: **{summary.get('min_smoothed_train_nll', 'n/a'):.4f}**"
        if isinstance(summary.get("min_smoothed_train_nll"), (int, float))
        else ""
    )
    final_val = summary.get("final_val_nll")
    if isinstance(final_val, (int, float)):
        lines.append(f"- Final val NLL: **{final_val:.4f}**")
    lines.append(f"- Final sampler URL: `{summary.get('final_sampler_path', 'n/a')}`")
    lines.append(f"- Final state URL:   `{summary.get('final_state_path', 'n/a')}`")
    lines.append("")

    # === Cost ===
    lines.append("## Cost")
    lines.append("")
    lines.append(f"- Tokens processed: **{summary.get('tokens_processed', 0):,}**")
    lines.append(f"- Loss tokens processed: **{summary.get('loss_tokens_processed', 0):,}**")
    lines.append(
        f"- Estimated cost (@ ${cfg.get('placeholder_usd_per_million_tokens', 0.4)}/1M tokens): "
        f"**${summary.get('estimated_cost_usd', 0):.4f}**"
    )
    lines.append(
        f"- Headroom vs cost cap: **${cfg.get('hard_cost_cap_usd', 0) - summary.get('estimated_cost_usd', 0):.2f}** "
        f"(cap = ${cfg.get('hard_cost_cap_usd', 0)})"
    )
    lines.append("> All prices are placeholders — calibrate against the real Tinker invoice before using these numbers in budget decisions.")
    lines.append("")

    # === Training curve ===
    lines.append("## Training curve")
    lines.append("")
    # Subsample metrics for the table
    if metrics:
        every = max(1, len(metrics) // 20)
        sampled = metrics[::every]
        lines.append("Train NLL at log intervals (subsampled to ~20 rows):")
        lines.append("")
        lines.append("| step | epoch | lr | train_nll | smoothed_nll | tokens_total | cost |")
        lines.append("|---:|---:|---:|---:|---:|---:|---:|")
        for m in sampled:
            lines.append(
                f"| {m['step']} | {m['epoch']} | {m['lr']:.2e} | "
                f"{m['train_nll']:.4f} | {m['smoothed_nll']:.4f} | "
                f"{m['tokens_total']:,} | ${m['estimated_cost_usd']:.4f} |"
            )
        lines.append("")
    if summary.get("val_losses"):
        lines.append("Val NLL checkpoints:")
        lines.append("")
        lines.append("| step | val_nll |")
        lines.append("|---:|---:|")
        for step, v in summary["val_losses"]:
            lines.append(f"| {step} | {v:.4f} |")
        lines.append("")
        lines.append("ASCII chart:")
        lines.append("")
        lines.append("```")
        lines.append(ascii_curve(summary["val_losses"]))
        lines.append("```")
        lines.append("")

    # === Test eval ===
    lines.append("## Test set evaluation")
    lines.append("")
    test_agg = eval_summary.get("test", {})
    if test_agg:
        lines.append(f"- Examples scored: **{test_agg.get('n', 0):,}**")
        lines.append(f"- Mean NLL (token-weighted): **{test_agg.get('mean_nll', float('nan')):.4f}**")
        if test_agg.get("by_question_type"):
            lines.append("")
            lines.append("By question type:")
            lines.append("")
            lines.append("| question_type | n | mean_nll |")
            lines.append("|---|---:|---:|")
            for qt, stats in sorted(test_agg["by_question_type"].items()):
                lines.append(f"| `{qt}` | {stats['n']:,} | {stats['mean_nll']:.4f} |")
        # per-source top 10 by example count
        if test_results:
            per_src: dict[str, list[float]] = defaultdict(list)
            for r in test_results:
                if not isinstance(r.get("mean_nll"), float) or r["mean_nll"] != r["mean_nll"]:
                    continue
                per_src[r["source_filename"]].append(r["mean_nll"])
            top = sorted(per_src.items(), key=lambda kv: -len(kv[1]))[:10]
            lines.append("")
            lines.append("Top-10 test sources (by example count):")
            lines.append("")
            lines.append("| source | n | mean_nll |")
            lines.append("|---|---:|---:|")
            for src, vs in top:
                lines.append(f"| `{src}` | {len(vs)} | {sum(vs)/len(vs):.4f} |")
    else:
        lines.append("_(test eval not run yet)_")
    lines.append("")

    # === Held-out eval ===
    lines.append("## Held-out-source evaluation")
    lines.append("")
    held_agg = eval_summary.get("held_out_source", {})
    if held_agg:
        lines.append(f"- Examples scored: **{held_agg.get('n', 0)}**")
        lines.append(f"- Mean NLL (token-weighted): **{held_agg.get('mean_nll', float('nan')):.4f}**")
        lines.append(
            "> Small sample (15 examples across 2 sources). Treat as a "
            "qualitative spot-check, not a statistical signal."
        )
    else:
        lines.append("_(held-out eval not run yet)_")
    lines.append("")

    # === Samples ===
    lines.append("## Sample generations")
    lines.append("")
    lines.append(
        f"Generated {len(samples)} responses from the trained adapter at "
        f"`temperature={0.3}`, `max_tokens={300}`, with prompts drawn "
        f"random.seed=42 from `test.jsonl`."
    )
    lines.append("")
    for i, s in enumerate(samples, 1):
        lines.append(f"### Sample {i} — `{s['pair_id']}` (`{s['question_type']}`)")
        lines.append("")
        lines.append(f"- **source:** `{s['source_filename']}`")
        lines.append("")
        lines.append("**Q:** " + s["user_question"])
        lines.append("")
        lines.append("**Reference:**")
        lines.append("")
        lines.append("> " + s["reference_answer"].replace("\n", "\n> "))
        lines.append("")
        lines.append("**Model:**")
        lines.append("")
        gen = s["model_generation"] or "_(empty)_"
        lines.append("> " + gen.replace("\n", "\n> "))
        lines.append("")

    # === Anything weird ===
    lines.append("## Anything weird")
    lines.append("")
    surprises = []
    if summary.get("abort_reason"):
        surprises.append(f"- **Abort reason:** `{summary['abort_reason']}`")
    else:
        surprises.append("- No guardrail (cost / walltime / divergence) tripped.")
    if isinstance(final_val, (int, float)) and isinstance(summary.get("val_losses"), list) and summary["val_losses"]:
        first_val = summary["val_losses"][0][1] if summary["val_losses"] else None
        if isinstance(first_val, (int, float)):
            delta = first_val - final_val
            surprises.append(
                f"- Val NLL change first → last eval: {first_val:.4f} → {final_val:.4f} "
                f"(Δ = {delta:+.4f}). Positive Δ = improvement."
            )
    if test_results:
        nlls = [r["mean_nll"] for r in test_results if isinstance(r.get("mean_nll"), float) and r["mean_nll"] == r["mean_nll"]]
        if nlls:
            surprises.append(
                f"- Test NLL distribution: min {min(nlls):.3f} / max {max(nlls):.3f} / "
                f"spread {max(nlls)-min(nlls):.3f} — outlier check for catastrophic per-example failures."
            )
    surprises.append(
        "- Pricing per token is a placeholder (ADR 0001, $0.40/1M); "
        "reconcile against the real Tinker invoice before quoting absolute $."
    )
    for s in surprises:
        lines.append(s)
    lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
